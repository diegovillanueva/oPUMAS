"Surface precipitation rates per column, m s⁻¹ (`prect`, `preci`)."
const SURFACE_PATHS = (prect = (:surface, :total), preci = (:surface, :ice))

"Every host output of the step, PUMAS name => (container, path)."
function output_paths()
    outputs = Pair{Symbol, Tuple}[]
    for (table, container) in ((TENDENCY_PATHS, :tendencies),
        (DIAGNOSTIC_PATHS, :diagnostics), (FLUX_PATHS, :diagnostics),
        (SURFACE_PATHS, :diagnostics), (PROCESS_RATE_PATHS, :process_rates))
        for (name, path) in pairs(table)
            golden = container == :process_rates ? Symbol("proc_rates_", name) : name
            push!(outputs, golden => (container, path...))
        end
    end
    return outputs
end

"The field at `path` (a tuple of Symbols) inside nested NamedTuples."
field_at(tree, path) = foldl(getproperty, path; init = tree)
